function savePost(e) {
  e.preventDefault();
  const id = document.getElementById("form-id").value;
  const title = document.getElementById("form-title").value.trim();
  const date = document.getElementById("form-date").value;
  const category = document.getElementById("form-category").value;
  const format = document.getElementById("form-format").value;
  const brand = document.getElementById("form-brand").value.trim();
  const status = document.getElementById("form-status").value;
  const hook = document.getElementById("form-hook") ? document.getElementById("form-hook").value.trim() : "";
  const refLink = document.getElementById("form-reflink") ? document.getElementById("form-reflink").value.trim() : "";
  const hashtags = document.getElementById("form-hashtags") ? document.getElementById("form-hashtags").value.trim() : "";
  const notes = document.getElementById("form-notes") ? document.getElementById("form-notes").value.trim() : "";

  if (id) {
    const idx = calendarPosts.findIndex(p => p.id === id);
    if (idx !== -1) {
      calendarPosts[idx] = {
        ...calendarPosts[idx],
        title,
        date,
        category,
        format,
        brand,
        status,
        platforms: [...selectedPlatforms], hook, refLink, hashtags, notes
      };
      showToast("Post berhasil diperbarui!");
    }
  } else {
    const newPost = {
      id: "post-" + Date.now(),
      title,
      date,
      category,
      format,
      brand,
      status,
      platforms: [...selectedPlatforms],
      notes: ""
    };
    calendarPosts.push(newPost);
    showToast("Post baru berhasil dijadwalkan!");
  }

  saveData();
  closePostModal();
  selectedDateStr = date;
  renderCurrentView();
  renderAgendaPanel();
}

function deleteCurrentPost() {
  if (!activeEditingId) return;
  if (confirm("Apakah Anda yakin ingin menghapus jadwal postingan ini?")) {
    calendarPosts = calendarPosts.filter(p => p.id !== activeEditingId);
    saveData();
    closePostModal();
    renderCurrentView();
    renderAgendaPanel();
    showToast("Postingan telah dihapus.");
  }
}

